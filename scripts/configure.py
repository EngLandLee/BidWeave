"""Prepare reproducible local configuration without committing credentials.

This script only writes .env and .runtime. It never contacts a service, making
configuration generation safe to run before Docker is available.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ENV = ROOT / ".env"
RUNTIME = ROOT / ".runtime"


def random_secret(length: int = 32) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = [
        "# Generated by scripts/configure.py; local credentials, never commit this file.",
    ]
    lines.extend(f"{key}={values[key]}" for key in sorted(values))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(path, 0o600)


