def write_runtime(env: dict[str, str]) -> None:
    RUNTIME.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(RUNTIME, 0o700)
    keycloak = RUNTIME / "keycloak"
    apisix = RUNTIME / "apisix"
    seaweed = RUNTIME / "seaweedfs"
    for directory in (keycloak, apisix, seaweed):
        directory.mkdir(parents=True, exist_ok=True)
    (keycloak / "bidweave-realm.json").write_text(
        json.dumps(realm(env), indent=2) + "\n", encoding="utf-8"
    )
    main_config = (ROOT / "infra" / "apisix" / "config.yaml").read_text(
        encoding="utf-8"
    )
    route_template = (ROOT / "infra" / "apisix" / "config.template.yaml").read_text(
        encoding="utf-8"
    )
    route_config = route_template.replace(
        "${APISIX_CLIENT_SECRET}", env["APISIX_CLIENT_SECRET"]
    )
    (apisix / "config.yaml").write_text(main_config, encoding="utf-8")
    (apisix / "apisix.yaml").write_text(route_config, encoding="utf-8")
    s3 = {
        "identities": [
            {
                "name": "bidweave",
                "credentials": [
                    {
                        "accessKey": env["S3_ACCESS_KEY"],
                        "secretKey": env["S3_SECRET_KEY"],
                    }
                ],
                "actions": [
                    "Read:bidweave",
                    "Write:bidweave",
                    "List:bidweave",
                    "Tagging:bidweave",
                    "Admin:bidweave",
                ],
            }
        ]
    }
    (seaweed / "s3.json").write_text(json.dumps(s3, indent=2) + "\n", encoding="utf-8")
    for path in (
        keycloak / "bidweave-realm.json",
        apisix / "config.yaml",
        apisix / "apisix.yaml",
        seaweed / "s3.json",
    ):
        os.chmod(path, 0o644)


def configure(env_path: Path, force: bool, llm_model: str | None = None) -> None:
    existing = read_env(env_path)
    if force or not existing.get("DATABASE_PASSWORD"):
        existing["DATABASE_PASSWORD"] = random_secret()
    defaults = {
        "APISIX_CLIENT_SECRET": random_secret(),
        "DEMO_PASSWORD": random_secret(24),
        "FLOWABLE_PASSWORD": random_secret(),
        "FUSEKI_ADMIN_PASSWORD": random_secret(),
        "KEYCLOAK_ADMIN_PASSWORD": random_secret(),
        "N8N_ENCRYPTION_KEY": random_secret(40),
        "S3_ACCESS_KEY": "bw" + random_secret(18),
        "S3_SECRET_KEY": random_secret(40),
        "FLOWABLE_USER": "flowable",
        "LLM_MODEL": "qwen2.5:1.5b",
    }
    for key, value in defaults.items():
        if force or not existing.get(key):
            existing[key] = value
    if llm_model is not None:
        if not llm_model or any(character.isspace() for character in llm_model):
            raise ValueError("model name must be nonempty and contain no whitespace")
        existing["LLM_MODEL"] = llm_model
    write_env(env_path, existing)
    write_runtime(existing)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", type=Path, default=DEFAULT_ENV)
    parser.add_argument(
        "--force",
        action="store_true",
        help="regenerate credentials for empty data volumes only; not live rotation",
    )
    parser.add_argument(
        "--llm-model", help="select a local model without rotating credentials"
    )
    args = parser.parse_args()
    configure(args.env_file.resolve(), args.force, args.llm_model)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
